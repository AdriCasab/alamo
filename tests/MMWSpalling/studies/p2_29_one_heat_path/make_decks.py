HU = {  # deck -> (kappa, rho, cp, beta=old alpha, E, nu)
    "granite": (2.50, 2640.0, 827.20, 8.0e-6, 29.98e9, 0.19),
    "sandstone": (4.96, 2480.0, 829.30, 1.0e-5, 16.63e9, 0.34),
}
HU_DECKS = [("hu_conduction", "input_granite2"), ("hu_conduction", "input_sandstone2"),
            ("hu_thermoelastic", "input_granite2"), ("hu_thermoelastic", "input_sandstone2"),
            ("hu_breakage_index", "input_granite2_37"), ("hu_breakage_index", "input_sandstone2_37"),
            ("hu_breakage_index", "input_sandstone2_89")]


def val(text, key):
    for ln in text.split("\n"):
        k = ln.split("#", 1)[0]
        if "=" in k and k.split("=", 1)[0].strip() == key:
            return k.split("=", 1)[1].strip()
    return None


def hu():
    res = []
    for d, name in HU_DECKS:
        rel = "validation/hu/%s/%s" % (d, name)
        text = open(os.path.join(T, rel)).read()
        rock = "granite" if "granite" in name else "sandstone"
        kappa, rho, cp, beta, E, nu = HU[rock]
        # the deck's own constants must be the table's (a guard on this script, not a choice)
        assert float(val(text, "material.constant.kappa")) == kappa and float(val(text, "material.constant.rho")) == rho
        assert float(val(text, "material.constant.cp")) == cp
        a = val(text, "alpha")
        assert a is not None and float(a.split()[0]) in (0.0, beta), (rel, a)
        mech = val(text, "el.type") == "static"
        if mech:   # the rock's elastic constants; off the mechanics decks the phase mirrors the deck's inert el.model1
            assert float(val(text, "el.model1.E")) == E and float(val(text, "el.model1.nu")) == nu, rel
        else:
            E, nu = float(val(text, "el.model1.E")), float(val(text, "el.model1.nu"))
        b = beta if mech else 0.0
        mu = E / (2.0 * (1.0 + nu))
        old_pf = val(text, "plot_file")
        new_pf = old_pf.replace("/output/", "/output_phase/")
        sub = [(r"^plot_file\b", "plot_file = " + new_pf)]
        changes = ("material.constant.* + the global `alpha` / `phase.T_ref` -> one constant phase (kappa %g, rho %g, "
                   "c_p %g, T_ref 280.15, beta = the old alpha %g, E %g, mu = E/(2(1 + nu)) = %.5g)%s"
                   % (kappa, rho, cp, b, E, mu, "" if mech else " (mechanics off: beta 0, E/mu inert)"))
        if d == "hu_breakage_index":
            # the USER, 2026-11-10: SINGLE LEVEL on the 40^3 base grid. AMR + mechanics fails on the production path
            # (MLMG aborts in the elastic solve at the first step after level 1 exists -- the same on bin_pre, so
            # pre-existing; the old deck on the old kernel runs). AMR is parked (SR 12). At 2.5 mm the explicit limit
            # with the prescribed top is 0.78 s (granite) / 0.37 s (sandstone), so every deck keeps timestep 0.2.
            assert int(val(text, "amr.max_level")) == 1
            sub += [(r"^amr\.max_level\b", "amr.max_level       = 0   # P2-29, the user: single level (AMR + mechanics "
                                            "fails on the production path)")]
            changes += "; amr.max_level 1 -> 0 (the user, 2026-11-10: AMR + mechanics fails on the production path)"
        blk = phase_block(kappa, rho, cp, 280.15, beta=b, E=E, mu="%.10g" % mu, inert_mech=not mech)
        res.append(write(rel, rel + "_phase" if name != "input" else rel.replace("input", "input_phase"),
                         lambda t, s=sub, k=blk: edit(t, drop=(r"^alpha\b", r"^phase\.", r"^material\."), sub=s,
                                                      insert_after=r"^geometry\.is_periodic\b", block=k),
                         changes + "."))
    return res


def main(argv):
    out = fixtures() + hu()
    bad = 0
    for dst, text in out:
        if "--check" in argv:
            ok = os.path.exists(dst) and open(dst).read() == text
            print("%s %s" % ("same " if ok else "DIFF ", os.path.relpath(dst, ROOT)))
            bad += not ok
        else:
            open(dst, "w").write(text)
            print("wrote %s" % os.path.relpath(dst, ROOT))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
