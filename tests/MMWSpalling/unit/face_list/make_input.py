#!/usr/bin/env python3
"""P2-8 unit/face_list -- generate ./input (provenance; run once, output committed).

The face list needs the whole Hoeser lab configuration (robin_form = surface,
surface.follow_mask, removal, the enthalpy march, microstructure), so the input is
the lab deck `validation/hoeser/input_lab` with the P2-7/what-if base leg's
command-line keys (`studies/whatif_uptake/legs/s100/argv.sh`) applied on top,
key for key, and then SHRUNK to a 12 mm cube at 1 mm with a linear h map whose
value differs on every face of a cell (so a wrong face centre is visible):
    h = 1000 + 20000 r + 5000 s     [W/m2K]
P2-10 drops the retired side-face and spall.lateral_* keys from the base.
Keys are unique in the output (the base's value replaced in place).
"""
import os
import shlex

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
DECK = os.path.join(ROOT, "tests", "MMWSpalling", "validation", "hoeser", "input_lab")
BASE = os.path.join(ROOT, "tests", "MMWSpalling", "studies", "whatif_uptake", "legs",
                    "s100", "argv.sh")

OVERRIDE = {
    "amr.n_cell": "12 12 12",
    "amr.max_grid_size": "6",
    "amr.blocking_factor": "2",
    "geometry.prob_lo": "0.0 0.0 0.0",
    "geometry.prob_hi": "0.012 0.012 0.012",
    "surface_patch.nozzle_z0": "0.0752",          # rock top 0.012 + 63.2 mm
    "surface_patch.h_expr": "1000.0+20000.0*r+5000.0*s",
    "timestep": "0.008",
    "stop_time": "0.016",                          # TWO steps: thermo writes step 1 at the next
    "amr.plot_int": "1",
    "amr.thermo.plot_int": "1",
    "amr.thermo.int": "1",
    "weibull.V0": "1.0e-9",
    "plot_file": "tests/MMWSpalling/unit/face_list/output/run",
}


def main():
    keys, order = {}, []
    for ln in open(DECK):
        s = ln.split("#", 1)[0].strip()
        if not s or "=" not in s:
            continue
        k, v = (x.strip() for x in s.split("=", 1))
        if k not in keys:
            order.append(k)
        keys[k] = v
    toks = shlex.split(open(BASE).read())
    start = next(n for n, t in enumerate(toks) if t.endswith("input_lab")) + 1
    for t in toks[start:]:
        k, v = t.split("=", 1)
        if k not in keys:
            order.append(k)
        keys[k] = v
    # P2-10: the side-face (group B + side_face_flux) and spall.lateral_* keys are
    # retired -- they abort when given -- so they are dropped from the base.
    for k in [k for k in order if k.startswith("surface_patch.side_face_")
              or k.startswith("spall.lateral_")]:
        order.remove(k)
        del keys[k]
    for k, v in OVERRIDE.items():
        if k not in keys:
            order.append(k)
        keys[k] = v
    with open(os.path.join(HERE, "input"), "w") as f:
        f.write("# P2-8 unit/face_list -- GENERATED by ./make_input.py (do not edit by hand):\n")
        f.write("# validation/hoeser/input_lab + studies/whatif_uptake/legs/s100/argv.sh,\n")
        f.write("# shrunk to a 12 mm cube at 1 mm with h = 1000 + 20000 r + 5000 s.\n")
        f.write("# The face-list key and the seeded cavities are given by ./test per leg.\n")
        for k in order:
            f.write(f"{k} = {keys[k]}\n")
    print(f"wrote {len(order)} keys")


if __name__ == "__main__":
    main()
